export function getPlayerAttackElement(weaponId: string, characterId: CharacterId): MonsterElement {
  if (weaponId === 'eq_solar_blade' || characterId === 'pyromancer') return 'fire';
  if (weaponId === 'eq_tide_spear' || weaponId === 'eq_abyssal_trident' || characterId === 'tidecaller') return 'water';
  if (weaponId === 'eq_sky_bow' || weaponId === 'eq_gale_blade' || characterId === 'skywarden') return 'storm';
  if (weaponId === 'eq_forge_hammer' || weaponId === 'eq_crystal_pick' || characterId === 'subterranean' || characterId === 'mountaineer') return 'earth';
  if (weaponId === 'eq_starfall_scepter' || weaponId === 'eq_aether_staff' || weaponId === 'eq_grapple_lantern' || characterId === 'mystic' || characterId === 'chronomancer') return 'light';
  if (characterId === 'riftwalker') return 'void';
  return 'light';
}

export function getElementalMultiplier(
  atkElement: MonsterElement,
  targetElement: MonsterElement,
  weakness: MonsterElement,
  resistance: MonsterElement
): { mult: number; label: 'WEAK' | 'RESIST' | 'NORMAL' } {
  if (atkElement === weakness) return { mult: 1.45, label: 'WEAK' };
  if (atkElement === resistance && atkElement !== targetElement) return { mult: 0.72, label: 'RESIST' };
  if (atkElement === targetElement && targetElement !== 'light') return { mult: 0.8, label: 'RESIST' };
  return { mult: 1, label: 'NORMAL' };
}
